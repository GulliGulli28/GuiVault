/** Le texte d'une erreur `{ code, message }` à montrer. */
export function errorText(code: string, message: string): string {
  if (language() === "fr") return message;
  if (code in BY_CODE) return BY_CODE[code];
  if (code.startsWith("invalid_")) return BY_CODE.invalid_request ?? message;
  return message;
}
